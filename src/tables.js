export const roll = (n, sides) => {
  let sum = 0;
  for (let i = 0; i < n; i++) sum += 1 + Math.floor(Math.random() * sides);
  return sum;
};

export const pick = (list) => list[Math.floor(Math.random() * list.length)];

export const tierOfCr = (cr) => {
  const n = cr.includes("/") ? 0 : Number(cr);
  return TIERS.find((t) => n >= t.min && n <= t.max) ?? TIERS[0];
};
